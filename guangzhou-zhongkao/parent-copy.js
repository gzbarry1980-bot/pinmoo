export function plainCopy(value){
 let text=String(value??'');
 text=text.replace(/(\d+)分封顶/g,'总分最多$1分');
 text=text.replace(/([高中低])置信度/g,(_,level)=>confidenceCopy(level).label);
 text=text.replace(/部分情景按同校最近年份位次折算（(\d+)%）/g,'约$1%的模拟借用了本校邻近年份记录，补充缺失数据');
 text=text.replace(/近年等位门槛跨度(\d+)分/g,'按排名换算后的历年录取门槛相差$1分');
 text=text.replace(/近年(\d+)%记录在第一志愿完成计划/g,'近年约$1%的记录显示：学校在第一志愿就已录满');
 for(const [from,to]of phrases)text=text.replaceAll(from,to);
 return text;
}
export function simplifyVisibleCopy(root){
 if(!root)return;
 const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);let node;
 while((node=walker.nextNode())){
  if(node.parentElement?.closest('script,style,textarea,input,.disclaimer,[data-copy-exact]'))continue;
  const next=plainCopy(node.nodeValue);if(next!==node.nodeValue)node.nodeValue=next;
 }
}
